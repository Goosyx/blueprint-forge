//! PT: Custo das simulações em blueprints sintéticas de ~100, ~1.000 e ~10.000 entidades: linhas
//!     de montadoras de engrenagem com esteira de entrada marcada e esteira de saída. Mede o tempo
//!     nativo (mediana de 5 rodadas) e grava as blueprints em `target/bench/` para o teste de
//!     tempo no WASM (`BF_BENCH=1 npx vitest run bench`).
//! EN: Cost of the simulations on synthetic blueprints of ~100, ~1,000 and ~10,000 entities: rows
//!     of gear assemblers with a marked input belt and an output belt. Measures native time (median
//!     of 5 runs) and writes the blueprints into `target/bench/` for the WASM timing test
//!     (`BF_BENCH=1 npx vitest run bench`).

use std::fs;
use std::path::Path;
use std::time::Instant;

use anyhow::{Result, anyhow};
use bf_blueprint::{BlueprintString, Limits, decode, encode_raw_json};
use bf_calc::{AnalysisOptions, calculate};
use bf_data::GameData;
use bf_world::{Topology, World};
use serde_json::{Value, json};

/// PT: Gera `rows` linhas de 10 montadoras. EN: Generates `rows` rows of 10 assemblers.
pub fn synthetic(rows: usize) -> Value {
    let mut entities = Vec::new();
    let mut add = |name: &str, x: f64, y: f64, extra: Value| {
        let mut entity = json!({"entity_number": entities.len() + 1, "name": name, "position": {"x": x, "y": y}});
        if let (Some(target), Value::Object(fields)) = (entity.as_object_mut(), extra) {
            target.extend(fields);
        }
        entities.push(entity);
    };
    for row in 0..rows {
        let y = (row * 9) as f64;
        add(
            "constant-combinator",
            -2.5,
            y + 0.5,
            json!({"control_behavior": {"sections": {"sections": [
                {"index": 1, "filters": [{"index": 1, "name": "iron-plate", "quality": "normal", "comparator": "=", "count": 1}]}
            ]}}}),
        );
        for x in -1..32 {
            add(
                "fast-transport-belt",
                f64::from(x) + 0.5,
                y + 0.5,
                json!({"direction": 4}),
            );
            add(
                "fast-transport-belt",
                f64::from(x) + 0.5,
                y + 6.5,
                json!({"direction": 4}),
            );
        }
        for k in 0..10 {
            let x = f64::from(1 + 3 * k);
            add("fast-inserter", x + 0.5, y + 1.5, json!({}));
            add(
                "assembling-machine-2",
                x + 0.5,
                y + 3.5,
                json!({"recipe": "iron-gear-wheel"}),
            );
            add("fast-inserter", x + 0.5, y + 5.5, json!({}));
        }
        add("medium-electric-pole", 32.5, y + 3.5, json!({}));
    }
    json!({"blueprint": {"item": "blueprint", "version": bf_blueprint::GAME_VERSION, "entities": entities}})
}

fn median(mut values: Vec<f64>) -> f64 {
    values.sort_by(f64::total_cmp);
    values.get(values.len() / 2).copied().unwrap_or(0.0)
}

pub fn run(assets: &Path, out_dir: &Path, report: &Path) -> Result<()> {
    let data = GameData::from_json(&fs::read_to_string(assets.join("gamedata.json"))?)?;
    fs::create_dir_all(out_dir)?;
    let mut table = String::from(
        "# Custo das simulações / Simulation cost\n\n\
         Gerado por / Generated by `bf-validate bench-sim` (nativo, release; mediana de 5 rodadas / \
         native, release; median of 5 runs). Tick: 600 ticks de aquecimento + 3600 de medição / \
         600 warm-up ticks + 3600 measured.\n\n\
         | Entidades / Entities | Análise / Analysis (ms) | Regime estável / Steady (ms) | Tick (ms) |\n|---:|---:|---:|---:|\n",
    );
    for rows in [1usize, 10, 95] {
        let json = synthetic(rows);
        let text = encode_raw_json(&json.to_string())?;
        fs::write(out_dir.join(format!("rows-{rows}.txt")), &text)?;
        let BlueprintString::Blueprint(blueprint) = decode(&text, &Limits::default())
            .map_err(|e| anyhow!("{e}"))?
            .content
        else {
            continue;
        };
        let count = blueprint.entities.len();
        let mut analysis_ms = Vec::new();
        let mut steady_ms = Vec::new();
        let mut tick_ms = Vec::new();
        for _ in 0..5 {
            let started = Instant::now();
            let world = World::build(&blueprint, &data).map_err(|e| anyhow!("{e}"))?;
            let topology = Topology::build(&world, &blueprint, &data);
            let options = AnalysisOptions::default();
            let calc =
                calculate(&data, &blueprint, &world, &options).map_err(|e| anyhow!("{e}"))?;
            let input = bf_sim::build(
                &data,
                &world,
                &topology,
                &calc,
                options.inserter_research,
                "coal",
            );
            analysis_ms.push(started.elapsed().as_secs_f64() * 1000.0);
            let started = Instant::now();
            bf_sim::steady::simulate(&input).map_err(|e| anyhow!("{e}"))?;
            steady_ms.push(started.elapsed().as_secs_f64() * 1000.0);
            let started = Instant::now();
            bf_sim::tick::simulate_with(
                &input,
                &bf_sim::tick::TickOptions {
                    warmup_ticks: 600,
                    measure_ticks: 3600,
                    ..bf_sim::tick::TickOptions::default()
                },
                &mut |_| true,
            )
            .map_err(|e| anyhow!("{e}"))?;
            tick_ms.push(started.elapsed().as_secs_f64() * 1000.0);
        }
        let line = format!(
            "| {count} | {:.1} | {:.1} | {:.1} |\n",
            median(analysis_ms),
            median(steady_ms),
            median(tick_ms)
        );
        print!("{line}");
        table.push_str(&line);
    }
    fs::write(report, table)?;
    Ok(())
}
